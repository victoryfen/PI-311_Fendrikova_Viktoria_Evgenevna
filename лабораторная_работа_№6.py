import tensorflow as tf
import numpy as np
import matplotlib.pyplot as plt
fashion_mnist=tf.keras.datasets.fashion_mnist
(train_images,train_labels),(test_images,test_labels)=fashion_mnist.load_data()

class_names = ['Футболка','Брюки','Свитер','Платье','Пальто','Сандалии','Рубашка','Кроссовки','Сумка','Ботинки']
for i in range(10):
    print(i,class_names[i])

plt.figure(figsize=(10,5))
for i in range(10):
    plt.subplot(2,5,i+1)
    plt.imshow(train_images[i],cmap='gray')
    plt.xlabel(class_names[train_labels[i]])
    plt.xticks([])
    plt.yticks([])
plt.show()

train_images=train_images/255.0
test_images=test_images/255.0

model = tf.keras.Sequential([
    tf.keras.layers.Flatten(input_shape=(28,28)),
    tf.keras.layers.Dense(128, activation='relu'),
    tf.keras.layers.Dense(10)])
model.summary()

model.compile(
    optimizer='adam',loss=tf.keras.losses.SparseCategoricalCrossentropy(from_logits=True),metrics=['accuracy'])
model.fit(train_images,train_labels,epochs=10)

test_loss,test_acc=model.evaluate(test_images,test_labels)
print('Точность:',test_acc)
print('Ошибка:',test_loss)

predictions=model.predict(test_images[:10])
plt.figure(figsize=(12,5))
for i in range(10):
    plt.subplot(2,5,i+1)
    plt.imshow(test_images[i],cmap='gray')
    predicted=np.argmax(predictions[i])
    actual=test_labels[i]
    plt.title(
        f'Прогноз:{class_names[predicted]}\n'
        f'Ответ:{class_names[actual]}')
    plt.axis('off')
plt.tight_layout()
plt.show()

indices = [np.where(test_labels == i)[0][0] for i in range(10)]
sample_images=test_images[indices]
predictions=model.predict(sample_images)
plt.figure(figsize=(12,6))
for i in range(10):
    plt.subplot(2,5,i+1)
    plt.imshow(sample_images[i],cmap='gray')
    predicted = np.argmax(predictions[i])
    plt.title(
        f'Прогноз: {class_names[predicted]}\n'
        f'Тип: {class_names[test_labels[indices[i]]]}')
    plt.axis('off')
plt.tight_layout()
plt.show()

